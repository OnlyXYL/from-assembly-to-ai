; ============================================================
; first.asm —— 人生第一批汇编指令
; 配套笔记 01，对应王爽《汇编语言（第4版）》第 1、2 章
;
; 用法：本文件供阅读对照；实际操作是在 DOSBox 的 debug 中
; 用 -a 命令逐行输入下列指令，再用 -t 单步执行观察寄存器。
; ============================================================

mov ax, 1       ; 将立即数 1 送入 AX 寄存器（AX = 0001）
                ; AX 是 16 位通用寄存器，可拆为 AH（高8位）+ AL（低8位）

mov bx, 2       ; 将立即数 2 送入 BX 寄存器（BX = 0002）

add ax, bx      ; AX = AX + BX = 0001 + 0002 = 0003
                ; 结果保存在 AX 中，BX 不变
